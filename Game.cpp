//=====================================================================
// 初期化処理
//=====================================================================
void InitGame(void)
{
	GetDevice()->SetRenderState(D3DRS_LIGHTING, FALSE);

	InitCamera();
	InitPolygon();
	InitGrid();
}

//=====================================================================
// 終了処理
//=====================================================================
void UninitGame(void)
{
	UninitCamera();
	UninitPolygon();
	UninitGrid();
}

//=====================================================================
// 更新処理
//=====================================================================
void UpdateGame(void)
{
	UpdateCamera();
	UpdatePolygon();
	UpdateGrid();
}

//=====================================================================
// 描画処理
//=====================================================================
void DrawGame(void)
{


	SetCamera(0);

	DrawPolygon();
	DrawGrid();
}